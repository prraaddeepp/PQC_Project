 /* ---------- reduction ---------- */
 static inline uint32_t reduce_shoup(uint32_t a, size_t i)
 {
     unsigned __int128 p = (unsigned __int128)a * R_val[i];
     uint32_t q = (uint32_t)(p >> 64);
     uint32_t n = PARAM_N - (uint32_t)i;
     uint32_t r = a - q * n;
     uint32_t mask = -(r >= n);
     return r - (n & mask);
 }
 
 /* ---------- self-test ---------- */
 static void validate_edge_cases(void)
 {
     for (size_t i = 0; i < TABLE_SZ; ++i) {
         uint32_t n = PARAM_N - (uint32_t)i;
         assert(reduce_shoup(0,      i) == 0);
         assert(reduce_shoup(n-1,    i) == n-1);
         assert(reduce_shoup(n,      i) == 0);
         assert(reduce_shoup(2U*n,   i) == 0);
     }
     puts("edge-case tests OK");
 }
 
 /* ---------- micro-benchmark harness ---------- */
 int main(void)
 {
     const size_t ITERS = 10000000, RUNS = 10;
     uint32_t *inp = aligned_alloc(64, ITERS*sizeof(uint32_t));
     for (size_t k = 0; k < ITERS; ++k)
         inp[k] = 0x9E3779B9u * k + 0x7F4A7C15u;
 
     validate_edge_cases();
 
     uint64_t cycles = 0, sum = 0;
     for (size_t r = 0; r < RUNS; ++r) {
         unsigned t; uint64_t t0 = __rdtscp(&t);
         for (size_t k = 0; k < ITERS; ++k)
             sum += reduce_shoup(inp[k], k % TABLE_SZ);
         uint64_t t1 = __rdtscp(&t);
         cycles += t1 - t0;
     }
 
     printf("checksum          %llu\n", (unsigned long long)sum);
     printf("avg cycles/call   %.3f\n",
            (double)cycles / (RUNS * ITERS));
 
     free(inp);
     return 0;
 }
 